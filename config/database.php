<?php

/*
|--------------------------------------------------------------------------
| Database Configuration
|--------------------------------------------------------------------------
*/

$host = "localhost";
$username = "root";
$password = "";
$database = "todo_app";


/*
|--------------------------------------------------------------------------
| Connect to MySQL
|--------------------------------------------------------------------------
*/

$conn = mysqli_connect(
    $host,
    $username,
    $password,
    $database
);


/*
|--------------------------------------------------------------------------
| Check Connection
|--------------------------------------------------------------------------
*/

if (!$conn) {

    die(
        "Database connection failed: " .
        mysqli_connect_error()
    );

}


/*
|--------------------------------------------------------------------------
| Character Set
|--------------------------------------------------------------------------
*/

mysqli_set_charset($conn, "utf8mb4");

?>

